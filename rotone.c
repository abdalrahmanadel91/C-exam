#include <unistd.h>

int main(int ac, char **av)
{
	int i = 0;
	char c;
		if (ac  == 2)
		{
			while(av[1][i])
			{
				c = av[1][i];
				if((av[1][i] >= 'a' && av[1][i] <= 'y') || (av[1][i] >= 'A' && av[1][i] <= 'Y') )
					c += 1;
				else if (av[1][i] == 'z')
					c = 'a';
				else if (av[1][i] == 'Z')
					c = 'A';
				write(1,&c,1);
				i++;
			}
		}
		write(1,"\n",1);
		return (0);
}
